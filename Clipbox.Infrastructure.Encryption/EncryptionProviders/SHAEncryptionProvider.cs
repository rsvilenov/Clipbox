using Clipbox.Infrastructure.Persistence;
using System;
using System.IO;
using System.Security.Cryptography;
using System.Text;

namespace Clipbox.Infrastructure.Encryption.EncryptionProviders
{
    public class SHAEncryptionProvider : IEncryptionProvider
    {
        private IPersistenceProvider _persistenceProvider;

        private const string AUTOGENERATED_KEY_NAME = "_k";

        private const int SHA_KEY_SIZE_BITS = 256;
        private const int SHA_BLOCK_SIZE_BITS = 128;

        private const int PASSWORD_SALT_SIZE_BYTES = 8;

        public SHAEncryptionProvider(IPersistenceProvider persistenceProvider)
        {
            _persistenceProvider = persistenceProvider;

            if (!_persistenceProvider.CheckIfKeyExists(AUTOGENERATED_KEY_NAME))
            {
                // generate a random byte sequence
                // which will be used as a key
                byte[] randomKey = GenerateRandomKey();
                StoreAutoGeneratedKey(randomKey);
            }
        }

        public byte[] Decrypt(byte[] cryptedData)
        {
            var aes = new RijndaelManaged
            {
                KeySize = SHA_KEY_SIZE_BITS,
                BlockSize = SHA_BLOCK_SIZE_BITS,
                Mode = CipherMode.CBC,
                Padding = PaddingMode.PKCS7
            };

            // the first n bytes in the crypted data are the IV, read them...
            const int ivSize = SHA_BLOCK_SIZE_BITS / 8;
            byte[] initVector = new byte[ivSize];
            Array.Copy(cryptedData, initVector, ivSize);
            
            // set the key
            aes.Key = ReadAutoGeneratedKeyFromStorage();
            // set the init vector
            aes.IV = initVector;

            // get the actual SHA encryted data, which starts after the IV bytes
            int actualEncryptedDataSize = cryptedData.Length - ivSize;
            byte[] actualEncryptedData = (byte[])Array.CreateInstance(typeof(byte), actualEncryptedDataSize);
            Array.Copy(cryptedData, ivSize, actualEncryptedData, 0, actualEncryptedDataSize);

            // now we are ready to decrypt
            using (MemoryStream ms = new MemoryStream())
            {
                using (var decryptor = aes.CreateDecryptor())
                using (CryptoStream cs = new CryptoStream(ms, decryptor, CryptoStreamMode.Write))
                {
                    cs.Write(actualEncryptedData, 0, actualEncryptedData.Length);
                }

                byte[] decryptedBytes = ms.ToArray();
                return decryptedBytes;
            }
        }

        public byte[] Decrypt(byte[] cryptedData, string password)
        {
            var aes = new RijndaelManaged
            {
                KeySize = SHA_KEY_SIZE_BITS,
                BlockSize = SHA_BLOCK_SIZE_BITS,
                Mode = CipherMode.CBC,
                Padding = PaddingMode.PKCS7
            };

            // the first n bytes in the crypted data are the salt, read them...
            byte[] saltBytes = new byte[PASSWORD_SALT_SIZE_BYTES];
            Array.Copy(cryptedData, saltBytes, PASSWORD_SALT_SIZE_BYTES);
            
            // get the password bytes
            byte[] passwordBytes = Encoding.UTF8.GetBytes(password);

            // derive bytes from the password and the salt
            var key = new Rfc2898DeriveBytes(passwordBytes, saltBytes, 1000);

            aes.Key = key.GetBytes(aes.KeySize / 8);
            aes.IV = key.GetBytes(aes.BlockSize / 8);
            
            // get the actual SHA encryted data, which starts after the salt bytes
            int actualEncryptedDataSize = cryptedData.Length - PASSWORD_SALT_SIZE_BYTES;
            byte[] actualEncryptedData = (byte[])Array.CreateInstance(typeof(byte), actualEncryptedDataSize);
            Array.Copy(cryptedData, PASSWORD_SALT_SIZE_BYTES, actualEncryptedData, 0, actualEncryptedDataSize);

            // now we are ready to decrypt
            using (MemoryStream ms = new MemoryStream())
            {
                using (var decryptor = aes.CreateDecryptor())
                using (CryptoStream cs = new CryptoStream(ms, decryptor, CryptoStreamMode.Write))
                {
                    cs.Write(actualEncryptedData, 0, actualEncryptedData.Length);
                }

                byte[] decryptedBytes = ms.ToArray();
                return decryptedBytes;
            }
        }

        public byte[] Encrypt(byte[] data)
        {
            var aes = new RijndaelManaged
            {
                KeySize = SHA_KEY_SIZE_BITS,
                BlockSize = SHA_BLOCK_SIZE_BITS,
                Mode = CipherMode.CBC,
                Padding = PaddingMode.PKCS7
            };

            aes.Key = ReadAutoGeneratedKeyFromStorage();

            aes.IV = GetRandomBytes(SHA_BLOCK_SIZE_BITS / 8);
            
            using (MemoryStream ms = new MemoryStream())
            {
                using (var encryptor = aes.CreateEncryptor())
                using (CryptoStream cs = new CryptoStream(ms, encryptor, CryptoStreamMode.Write))
                {
                    cs.Write(data, 0, data.Length);
                }

                byte[] encryptedBytes = ms.ToArray();

                // Create a new byte array to store both the 
                // initialization vector and the encrypted data.
                var encryptedData = new byte[encryptedBytes.Length + aes.IV.Length];

                // Copy the IV to the data. It is basically used as a salt so it is
                // safe to store it unprotected and to pass it here and there...
                aes.IV.CopyTo(encryptedData, 0);

                // Now append the actual encrypted data. We know the size of
                // the initialization vector, so during decryption, we can
                // read it from the byte array and use it to decrypt the 
                // actual encrypted data.
                encryptedBytes.CopyTo(encryptedData, aes.IV.Length);

                return encryptedData;
            }

        }

        public byte[] Encrypt(byte[] data, string password)
        {
            var aes = new RijndaelManaged
            {
                KeySize = SHA_KEY_SIZE_BITS,
                BlockSize = SHA_BLOCK_SIZE_BITS,
                Mode = CipherMode.CBC,
                Padding = PaddingMode.PKCS7
            };
            
            // Get some random bytes to use as salt. 
            // The salt should be at least 8 bytes.
            byte[] saltBytes = GetRandomBytes(PASSWORD_SALT_SIZE_BYTES);
            
            // get the password bytes
            byte[] passwordBytes = Encoding.UTF8.GetBytes(password);

            // derive bytes from the password and the salt
            var key = new Rfc2898DeriveBytes(passwordBytes, saltBytes, 1000);
            
            aes.Key = key.GetBytes(aes.KeySize / 8);
            aes.IV = key.GetBytes(aes.BlockSize / 8);


            using (MemoryStream ms = new MemoryStream())
            {
                using (var encryptor = aes.CreateEncryptor())
                using (CryptoStream cs = new CryptoStream(ms, encryptor, CryptoStreamMode.Write))
                {
                    cs.Write(data, 0, data.Length);
                }

                byte[] encryptedBytes = ms.ToArray();

                // Create a new byte array to store both the 
                // salt and the encrypted data. This time we
                // will be storing the salt and not the
                // IV itself, because we will use Rfc2898DeriveBytes
                // again during the decryption step.
                var encryptedData = new byte[encryptedBytes.Length + saltBytes.Length];

                // Copy the salt to the data. It is basically used as a salt so it is
                // safe to store it unprotected and to pass it here and there...
                saltBytes.CopyTo(encryptedData, 0);

                // Now append the actual encrypted data. We know the size of
                // the salt, so during decryption, we can
                // read it from the byte array and use it to decrypt the 
                // actual encrypted data.
                encryptedBytes.CopyTo(encryptedData, saltBytes.Length);

                return encryptedData;
            }
        }
        
        private void StoreAutoGeneratedKey(byte[] key)
        {
            // use DpApi to protect the key.
            byte[] dpApiProtectedKey = ProtectedData.Protect(key, null, DataProtectionScope.CurrentUser);
            
            // store the protected key in a file
            _persistenceProvider.Write(AUTOGENERATED_KEY_NAME, dpApiProtectedKey);
        }

        private byte[] ReadAutoGeneratedKeyFromStorage()
        {
            // read the DpApi protected key from storage
            byte[] dpApiProtectedKey = _persistenceProvider.ReadBytes(AUTOGENERATED_KEY_NAME);

            // unprotect and return the key
            return ProtectedData.Unprotect(dpApiProtectedKey, null, DataProtectionScope.CurrentUser);
        }

        private byte[] GenerateRandomKey()
        {
            return GetRandomBytes(SHA_KEY_SIZE_BITS / 8);
        }

        private byte[] GetRandomBytes(int numberOfBytes)
        {
            byte[] ba = (byte[])Array.CreateInstance(typeof(byte), numberOfBytes);

            using (var randomGenerator = RNGCryptoServiceProvider.Create())
            {
                randomGenerator.GetBytes(ba);
            }

            return ba;
        }
    }
}
